import { chromium } from 'playwright';
const out = '../reference/screens/mejoras/mobile/';
import fs from 'node:fs'; fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch(); const errors = [];
const p = await b.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, locale: 'es-CL' });
p.on('pageerror', e => errors.push(e.message));
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await p.screenshot({ path: out + '390-hero.png' });
const go = async sel => { await p.evaluate(s => { const e = document.querySelector(s); scrollTo({ top: e.getBoundingClientRect().top + scrollY - 180, behavior: 'instant' }); }, sel); await p.waitForTimeout(700); };
await go('.valores'); await p.screenshot({ path: out + '390-valores.png' });
const info = await p.evaluate(() => { const v = document.querySelector('.valores'); return { scrollable: v.scrollWidth > v.clientWidth, cards: v.children.length, cardW: Math.round(v.children[0].getBoundingClientRect().width) }; });
console.log('valores slider:', JSON.stringify(info));
await p.$eval('.valores', v => v.scrollBy({ left: 330 })); await p.waitForTimeout(700);
await p.screenshot({ path: out + '390-valores-deslizado.png' });
await go('#directorio'); await p.screenshot({ path: out + '390-directorio.png' });
console.log('directorio slider:', JSON.stringify(await p.evaluate(() => { const c = document.querySelector('#directorio .accordion__content'); return { scrollable: c.scrollWidth > c.clientWidth, cards: c.querySelectorAll('.team-card').length }; })));
await p.locator('#gerencia summary').tap(); await p.waitForTimeout(900);
await go('#gerencia'); 
console.log('gerencia slider:', JSON.stringify(await p.evaluate(() => { const c = document.querySelector('#gerencia .accordion__content'); const cards = [...c.querySelectorAll('.team-card')]; return { scrollable: c.scrollWidth > c.clientWidth, cards: cards.length, mismaFila: new Set(cards.map(x => Math.round(x.getBoundingClientRect().top))).size === 1 }; })));
await p.screenshot({ path: out + '390-gerencia.png' });
await p.$eval('#gerencia .accordion__content', c => c.scrollTo({ left: c.scrollWidth })); await p.waitForTimeout(700);
await p.screenshot({ path: out + '390-gerencia-final.png' });
await b.close(); console.log('errores JS:', errors.length ? errors : 'ninguno');
